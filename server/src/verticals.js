// بيرجّع أول مجال ممنوع في الكلمات، أو null
export function bannedIn(words) {
  for (const w of words || []) {
    const t = tok(w);
    for (const [key, label, marks] of BANNED) if (marks.some((m) => hasWord(t, m))) return { key, label, word: w };
  }
  return null;
}
