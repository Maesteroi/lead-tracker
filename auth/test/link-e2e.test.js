// اللينك اللي كود الشيت بيطلّعه (apps-script/oauth.js) لازم خدمة الربط تقبله بالظبط.
// الاختبار ده بيشغّل الكودين مع بعض علشان الصيغة ماتختلفش بين الطرفين.
import test from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { readFileSync } from 'node:fs';
import worker from '../worker.js';

const code = readFileSync(new URL('../../apps-script/oauth.js', import.meta.url), 'utf8');
const props = { LINK_SECRET: 'shared-link-secret', SITE_abc123xyz: '{"n":"روضة","k":"k1"}' };
const ctx = {
  PropertiesService: { getScriptProperties: () => ({ getProperty: (k) => (props[k] === undefined ? null : props[k]), getProperties: () => Object.assign({}, props) }) },
  Utilities: { computeHmacSha256Signature: (m, s) => Array.from(createHmac('sha256', s).update(m).digest()) },
  siteRec_: (id) => (props['SITE_' + id] ? JSON.parse(props['SITE_' + id]) : null),
  Logger: { log() {} }, console: { log() {}, error() {} },
};
const sheet = new Function(...Object.keys(ctx), code + ';return { adsConnectLink_ };')(...Object.values(ctx));
const ENV = { GOOGLE_CLIENT_ID: 'cid', GOOGLE_CLIENT_SECRET: 'cs', HMAC_SECRET: 'h', APPS_SCRIPT_URL: 'https://script.example/exec', LINK_SECRET: 'shared-link-secret' };
const open = (url, env) => worker.fetch(new Request(url), env || ENV);

test('a link generated by the sheet is accepted by the connect service', async () => {
  const url = sheet.adsConnectLink_('abc123xyz');
  assert.match(url, /^https:\/\/auth\.maestrolt\.com\/connect\?site_id=abc123xyz&exp=\d{10}&sig=[0-9a-f]{64}$/);
  const res = await open(url);
  assert.equal(res.status, 302);
  assert.ok(res.headers.get('Location').startsWith('https://accounts.google.com/o/oauth2/v2/auth?'));
});

test('the same link stops working after 15 minutes', async () => {
  const sixteenMinAgo = Date.now() - 16 * 60 * 1000;
  assert.equal((await open(sheet.adsConnectLink_('abc123xyz', sixteenMinAgo))).status, 403);
  const fourteenMinAgo = Date.now() - 14 * 60 * 1000;
  assert.equal((await open(sheet.adsConnectLink_('abc123xyz', fourteenMinAgo))).status, 302);
});

test('a link made with a different secret is rejected', async () => {
  const url = sheet.adsConnectLink_('abc123xyz');
  assert.equal((await open(url, Object.assign({}, ENV, { LINK_SECRET: 'other' }))).status, 403);
});
